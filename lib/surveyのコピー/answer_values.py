# -*- coding: utf-8 -*-
# auth_portal_app/lib/survey/answer_values.py
# ============================================================
# 社内アンケート 特別回答値
#
# 機能：
# - 「該当なし」の保存値を定義する
# - 「回答しない」の保存値を定義する
# - 特別回答値の判定と表示名変換を行う
#
# 方針：
# - 空文字やNoneとは区別して保存する
# - UI・回答検証・保存・集計で同じ値を使用する
# - JSONへそのまま保存できる文字列を使用する
# ============================================================

from __future__ import annotations

# ============================================================
# 特別回答値
# ============================================================
SURVEY_ANSWER_NONE = "__SURVEY_NONE__"
SURVEY_ANSWER_SKIP = "__SURVEY_SKIP__"


# ============================================================
# 特別回答値一覧
# ============================================================
SURVEY_SPECIAL_ANSWER_VALUES = frozenset(
    {
        SURVEY_ANSWER_NONE,
        SURVEY_ANSWER_SKIP,
    }
)


# ============================================================
# 表示名
# ============================================================
SURVEY_SPECIAL_ANSWER_LABELS = {
    SURVEY_ANSWER_NONE: "該当なし",
    SURVEY_ANSWER_SKIP: "回答しない",
}


# ============================================================
# 特別回答値判定
# ============================================================
def is_survey_special_answer(
    value: object,
) -> bool:
    # ------------------------------------------------------------
    # 完全一致する文字列だけを特別回答として扱う
    # ------------------------------------------------------------
    return (
        isinstance(
            value,
            str,
        )
        and value in SURVEY_SPECIAL_ANSWER_VALUES
    )


# ============================================================
# 「該当なし」判定
# ============================================================
def is_survey_none_answer(
    value: object,
) -> bool:
    return value == SURVEY_ANSWER_NONE


# ============================================================
# 「回答しない」判定
# ============================================================
def is_survey_skip_answer(
    value: object,
) -> bool:
    return value == SURVEY_ANSWER_SKIP


# ============================================================
# 表示名取得
# ============================================================
def get_survey_special_answer_label(
    value: object,
) -> str | None:
    # ------------------------------------------------------------
    # 特別回答値でない場合はNoneを返す
    # ------------------------------------------------------------
    if not isinstance(
        value,
        str,
    ):
        return None

    return SURVEY_SPECIAL_ANSWER_LABELS.get(
        value,
    )