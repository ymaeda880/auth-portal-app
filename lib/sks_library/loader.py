# auth_portal_app/lib/sks_library/loader.py
# ============================================================
# SKSライブラリー 蔵書データ読み込み
#
# 機能：
# - SKS_booklist.csv を文字列として読み込む
# - 完全な空行を除外する
# - セル内の不要な前後空白を整理する
# - AI検索・通常検索で使用する内部IDを付与する
#
# 方針：
# - NDC，発行年，棚番号なども数値・日付へ変換しない
# - 元CSVは変更しない
# - 内部IDは読み込み時に一時的に付与する
# ============================================================

from __future__ import annotations

# ============================================================
# imports
# ============================================================
from pathlib import Path
import unicodedata

import pandas as pd


# ============================================================
# 定数
# ============================================================
SKS_COLUMNS = [
    "分類: NDC",
    "棚番号-段",
    "タイトル",
    "編著者",
    "発行者",
    "発行年",
    "言語",
    "注記：原著名／仮訳、ISBN等",
    "貴重書",
    "タグ",
]

INTERNAL_ID_COLUMN = "_sks_id"


# ============================================================
# helper：セル文字列整理
# ============================================================
def _clean_cell(value: object) -> str:
    """
    CSVセルを検索用の安全な文字列へ整える．
    """

    text = str(value or "")

    # ------------------------------------------------------------
    # NBSP 等を通常スペースへ
    # ------------------------------------------------------------
    text = text.replace("\u00a0", " ")
    text = text.replace("\u3000", " ")

    # ------------------------------------------------------------
    # 改行コード統一
    # ------------------------------------------------------------
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # ------------------------------------------------------------
    # 前後空白除去
    # ------------------------------------------------------------
    return text.strip()


# ============================================================
# helper：検索比較用文字列
# ============================================================
def normalize_for_search(value: object) -> str:
    """
    AND / OR検索で使用する比較用文字列を作る．
    表示値そのものは変更しない．
    """

    text = _clean_cell(value)

    # ------------------------------------------------------------
    # 全角・半角などを検索時だけ正規化
    # ------------------------------------------------------------
    text = unicodedata.normalize("NFKC", text)

    return text.casefold()


# ============================================================
# CSV読み込み
# ============================================================
def load_sks_booklist(
    csv_path: Path | str,
) -> pd.DataFrame:
    """
    SKS_booklist.csv を読み込み，
    検索用DataFrameを返す．
    """

    path = Path(csv_path)

    if not path.exists():
        raise FileNotFoundError(
            f"SKS蔵書データが見つかりません: {path}"
        )

    # ------------------------------------------------------------
    # CSV読み込み
    #
    # 全項目を文字列で取得する．
    # Excel的な日付・数値への自動変換を行わない．
    # ------------------------------------------------------------
    read_error: Exception | None = None
    df: pd.DataFrame | None = None

    for encoding in (
        "utf-8-sig",
        "utf-8",
        "cp932",
    ):
        try:
            df = pd.read_csv(
                path,
                dtype=str,
                keep_default_na=False,
                encoding=encoding,
            )
            break

        except UnicodeDecodeError as e:
            read_error = e

    if df is None:
        raise RuntimeError(
            f"SKS蔵書データの文字コードを判定できませんでした: {path}"
        ) from read_error

    # ------------------------------------------------------------
    # 列名整理
    # ------------------------------------------------------------
    df.columns = [
        str(col).replace("\ufeff", "").strip()
        for col in df.columns
    ]

    # ------------------------------------------------------------
    # 必須列確認
    # ------------------------------------------------------------
    missing_columns = [
        col
        for col in SKS_COLUMNS
        if col not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            "SKS蔵書データに必要な列がありません: "
            + ", ".join(missing_columns)
        )

    # ------------------------------------------------------------
    # SKSで使用する10列だけ取得
    # ------------------------------------------------------------
    df = df[SKS_COLUMNS].copy()

    # ------------------------------------------------------------
    # 全セル文字列整理
    # ------------------------------------------------------------
    for col in SKS_COLUMNS:
        df[col] = df[col].map(_clean_cell)

    # ------------------------------------------------------------
    # 完全空行除去
    #
    # NDC等が空欄でも，他の列に値があれば残す．
    # ------------------------------------------------------------
    non_empty_mask = (
        df[SKS_COLUMNS]
        .apply(
            lambda row: any(
                str(value or "").strip()
                for value in row
            ),
            axis=1,
        )
    )

    df = df.loc[non_empty_mask].copy()

    # ------------------------------------------------------------
    # index再構成
    # ------------------------------------------------------------
    df.reset_index(
        drop=True,
        inplace=True,
    )

    # ------------------------------------------------------------
    # タイトル確認
    # ------------------------------------------------------------
    title_empty = (
        df["タイトル"]
        .astype(str)
        .str.strip()
        .eq("")
    )

    if title_empty.any():
        # タイトル空欄行は検索結果として意味を持たないため除外
        df = df.loc[~title_empty].copy()
        df.reset_index(
            drop=True,
            inplace=True,
        )

    # ------------------------------------------------------------
    # 内部ID
    #
    # CSVそのものへは書き込まない．
    # ------------------------------------------------------------
    df.insert(
        0,
        INTERNAL_ID_COLUMN,
        [
            f"SKS{i:06d}"
            for i in range(1, len(df) + 1)
        ],
    )

    return df


# ============================================================
# AI送信用：1冊分文字列
# ============================================================
def build_ai_book_line(
    row: pd.Series,
) -> str:
    """
    AIへ送る1冊分の圧縮された書誌情報を作る．

    棚番号と貴重書はAIの検索判断には使用せず，
    最終表示時に元DataFrameから取得する．
    """

    parts: list[str] = []

    # ------------------------------------------------------------
    # ID
    # ------------------------------------------------------------
    sks_id = str(
        row.get(INTERNAL_ID_COLUMN, "")
        or ""
    ).strip()

    parts.append(sks_id)

    # ------------------------------------------------------------
    # AI判断に使用する書誌項目
    # ------------------------------------------------------------
    ai_columns = [
        "分類: NDC",
        "タイトル",
        "編著者",
        "発行者",
        "発行年",
        "言語",
        "注記：原著名／仮訳、ISBN等",
        "タグ",
    ]

    for col in ai_columns:
        value = str(
            row.get(col, "")
            or ""
        ).strip()

        if value:
            parts.append(
                f"{col}={value}"
            )

    return " | ".join(parts)


# ============================================================
# AI送信用：蔵書一覧
# ============================================================
def build_ai_catalog_text(
    df: pd.DataFrame,
) -> str:
    """
    DataFrame全体をAI検索用の文字列へ変換する．
    """

    lines = [
        build_ai_book_line(row)
        for _, row in df.iterrows()
    ]

    return "\n".join(lines)