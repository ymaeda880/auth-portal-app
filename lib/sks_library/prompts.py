# -*- coding: utf-8 -*-
# auth_portal_app/lib/sks_library/prompts.py
# ============================================================
# SKSライブラリー AI検索プロンプト
#
# 機能：
# - AI検索用system promptを生成する
# - 蔵書一覧を含むuser promptを生成する
# - 分割検索後の最終ランキング用promptを生成する
#
# 方針：
# - AIは蔵書を選択するだけ
# - 正式な書誌情報はAIに生成させない
# - AIが選択した理由を必ず出力する
# ============================================================

from __future__ import annotations


# ============================================================
# system prompt
# ============================================================
def build_sks_ai_search_system_prompt() -> str:
    return """
あなたは，専門図書館の蔵書検索を支援するAIです．

あなたの役割は，提示されたSKSライブラリーの蔵書一覧の中から，
利用者の質問・調査目的に関連する書籍を選択することです．

必ず次の規則を守ってください．

1. 提示された蔵書一覧に存在する書籍だけを選択してください．
2. 存在しない書籍を追加してはいけません．
3. タイトル，編著者，発行者，発行年などの正式な書誌情報を
   あなた自身で生成しないでください．
4. 書籍の選択には，提示された次の情報を使用してください．
   - 分類: NDC
   - タイトル
   - 編著者
   - 発行者
   - 発行年
   - 言語
   - 注記
   - タグ
5. 日本語の質問から外国語タイトルの関連書籍を選択して構いません．
6. 表記が完全一致しなくても，意味的に関連する書籍を選択して構いません．
7. 各書籍について，その書籍を選択した理由を日本語で説明してください．
8. 選択理由は，提示された書誌情報だけを根拠にしてください．
9. 本文を実際に読んだかのような内容説明をしてはいけません．
10. 書誌情報から確認できない内容を推測してはいけません．
11. 関連性の低い書籍を，件数合わせのために選択してはいけません．
12. AI関連度は0から100の整数で示してください．
13. AI関連度は確率ではなく，質問との相対的な関連性を示す評価値です．
14. 関連性の高い順に並べてください．

出力は必ずJSONだけにしてください．
Markdownのコードブロックは使用しないでください．

出力形式：

{
  "results": [
    {
      "id": "SKS000001",
      "score": 95,
      "reason": "この書籍を選択した理由"
    }
  ]
}

該当する書籍がない場合：

{
  "results": []
}
""".strip()


# ============================================================
# 通常AI検索 user prompt
# ============================================================
def build_sks_ai_search_user_prompt(
    *,
    query: str,
    catalog_text: str,
    max_results: int = 20,
) -> str:
    return f"""
【利用者の質問・調査目的】

{str(query or "").strip()}


【検索条件】

次のSKSライブラリー蔵書一覧から，
質問・調査目的との関連性が高い書籍を選択してください．

最大選択件数：{int(max_results)}冊

関連する資料が少ない場合は，
最大件数まで無理に選択しないでください．


【SKSライブラリー蔵書一覧】

{catalog_text}
""".strip()


# ============================================================
# 分割検索：最終ランキング prompt
# ============================================================
def build_sks_ai_rerank_prompt(
    *,
    query: str,
    candidates_text: str,
    max_results: int = 20,
) -> str:
    return f"""
【利用者の質問・調査目的】

{str(query or "").strip()}


【処理内容】

SKSライブラリーの蔵書一覧を複数のグループに分けて検索した結果，
次の書籍が候補として選ばれました．

候補全体を改めて比較し，
質問・調査目的との関連性が高い順に選択してください．

最大選択件数：{int(max_results)}冊

関連性が低い候補は除外してください．
件数合わせのために選択してはいけません．

各書籍について，

- id
- score
- reason

を返してください．

reasonは，ここに提示された書誌情報だけを根拠にしてください．


【候補書籍】

{candidates_text}
""".strip()