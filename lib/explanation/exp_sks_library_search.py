# ============================================================
# ページ上部説明UI
# ============================================================
def render_sks_library_search_page_intro() -> None:

    # ------------------------------------------------------------
    # AI利用について
    # ------------------------------------------------------------
    render_info_card_compact(
        body_html="""
🟡 このページでは，通常の<b>キーワード検索</b>に加えて，生成AIを利用した<b>AI検索</b>を使用できます．
AI検索では，SKSライブラリーの蔵書情報をもとに，質問に関連する書籍をAIが選択します．
""",
    )

    # ------------------------------------------------------------
    # 使い方
    # ------------------------------------------------------------
    render_info_card_bullets_compact_custom(
        title="使い方 📚",
        items=[
            (
                "",
                "キーワード検索では，タイトル，編著者，発行者などから蔵書を検索できます．",
            ),
            (
                "",
                "AI検索では，「庭園に関する書籍を探して」のように，自由な文章で蔵書を探すことができます．",
            ),
            (
                "",
                "AI検索では，AIが選択した理由と関連度を検索結果とともに表示します．",
            ),
            (
                "",
                "検索結果は，Text，Word，PDF，Excel形式でダウンロードできます．",
            ),
        ],
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )


# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_sks_library_search_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "light_green",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


