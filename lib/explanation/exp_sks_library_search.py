# 詳細説明：AI検索
# ============================================================
SKS_LIBRARY_AI_TEXT = """

##### 1. AI検索

AI検索では，通常のキーワード一致だけではなく，
質問の意味をもとに関連する蔵書を探します．

日本語で質問した場合でも，
関連すると判断される外国語タイトルの書籍が選択される場合があります．

---

##### 2. AIが選択した理由

AI検索では，各書籍について，

- AI関連度
- AIが選択した理由

を表示します．

AI関連度は，質問との関連性を示す参考値です．
確率を示すものではありません．

---

##### 3. 書誌情報について

タイトル，編著者，発行者，発行年，棚番号などの書誌情報は，
AIが生成したものではありません．

AIはSKSライブラリーの蔵書を選択し，
正式な書誌情報は蔵書データから取得して表示します．

---

##### 4. 選択理由について

AIが選択した理由は，
AIに提示されたタイトル，編著者，発行者，発行年，注記などの
蔵書情報をもとに生成されます．

本の本文をAIが読んで判断しているものではありません．

"""


