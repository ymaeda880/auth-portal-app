SURVEYTEX_OVERVIEW_TEXT = r"""
##### 1. SurveyTexとは

SurveyTexは，社内アンケートの内容をテキスト形式で定義するための記述形式です．

拡張子は `.svtex` を使用します．

アンケートのタイトル，説明，質問，選択肢，必須設定，条件分岐などを1つのファイルに記述します．

---

##### 2. 基本構成

SurveyTexファイルは，主に次の内容で構成します．

- アンケートID
- バージョン
- タイトル
- 説明
- 回答完了メッセージ
- 質問
- 選択肢
- 条件分岐

基本的な記述例は次のとおりです．

```text
\id{survey_2026_08}
\version{1}
\title{PAIS利用状況アンケート}

\description{
PAISの利用状況についてお尋ねします．
}

\begin{radio,
id="proofreading_use",
label="文章校正",
required=true,
skip_button=true
}

\question{「文章校正」を使用したことがありますか？}

\options{
1|使用したことがある
0|使用したことがない
}

\end{radio}
```

---

##### 3. 質問の記述

質問は，次の形式で記述します．

```text
\begin{質問形式,
属性
}

\question{質問文}

\options{
選択肢
}

\end{質問形式}
```

質問形式によっては `\options{...}` を使用しません．

---

##### 4. 質問ID

各質問には，一意の質問IDを設定します．

```text
id="proofreading_use"
```

質問IDは，回答データと質問を対応させるために使用します．

アンケートの回答受付開始後は，既存の質問IDを変更しないでください．

---

##### 5. 保存値と表示名

選択肢では，保存値と回答者に表示する名称を分けることができます．

```text
\options{
1|使用したことがある
0|使用したことがない
}
```

この場合，

- `1` が保存値
- `使用したことがある` が表示名
- `0` が保存値
- `使用したことがない` が表示名

となります．

条件分岐では，原則として保存値を使用します．

```text
show_if="proofreading_use=='1'"
```

---

##### 6. 回答のスキップ

質問に，

```text
skip_button=true
```

を設定すると，回答者は「回答をスキップする」を選択できます．

「回答をスキップする」は通常の選択肢とは別の特別回答として扱うため，`\options{...}` の中へ追加する必要はありません．

回答画面の「以降の回答をスキップ」はSurveyTexの属性ではなく，回答画面側の共通機能です．

---

##### 7. 登録前の確認

SurveyTexファイルを登録すると，構文チェックを行います．

登録前には，特に次の点を確認してください．

- 質問IDが重複していないか
- `\begin` と `\end` が対応しているか
- 選択式質問に選択肢が設定されているか
- `show_if` の参照先が正しいか
- `show_if` で保存値を正しく指定しているか
"""

