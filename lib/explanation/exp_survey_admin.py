SURVEYTEX_OVERVIEW_TEXT = r"""
##### 1. SurveyTexとは

SurveyTexは，社内アンケートの内容をテキストで記述するための独自マークアップ言語です。

拡張子は `.svtex` です。アンケートの基本情報，質問形式，質問文，選択肢，必須設定，条件分岐などを記述します。

---

##### 2. 基本的な記述形式

基本情報は，バックスラッシュから始まる命令で記述します。

```text
\title{PAIS利用状況アンケート}
```

質問は，`\\begin{質問形式,...}` から `\\end{質問形式}` までの質問ブロックとして記述します。

```text
\begin{radio,
id="q1",
label="PAIS利用経験",
required=true
}

\question{PAISを利用したことがありますか？}

\options{
1|使用したことがある
0|使用したことがない
}

\end{radio}
```

`\\begin{...}` の最初の値が質問形式です。続けて指定する属性は，カンマで区切ります。

---

##### 3. 使用できる文字

SurveyTexファイルはUTF-8で保存してください。UTF-8 BOMが付いている場合も読み込めますが，原則としてBOMなしUTF-8を推奨します。

---

##### 4. コメント

`%` 以降は，その行のコメントとして扱います。ただし，引用符で囲まれた属性値の中にある `%` はコメント開始として扱いません。

```text
% この行はコメントです
\title{PAIS利用状況アンケート}  % アンケートタイトル
```

---

##### 5. 空行

空行は解析結果に影響しません。基本情報と各質問ブロックの間に空行を入れると読みやすくなります。
"""

