SURVEY_STORAGE_TEXT = """
##### 1. 保存場所

アンケート関連データは，次の管理者領域に保存します。

```text
projects/Storages/_admin/survey/
```

実際の保存ルートは，PAISのストレージ設定に基づいて解決します。

---

##### 2. 保存するデータ

次のデータを保存します。

- SurveyTex原本
- 解析済みアンケート定義
- アンケート管理情報
- ユーザー回答
- 回答更新履歴
- 集計に必要な管理情報

---

##### 3. 回答の上書き

ユーザーが再回答した場合は，最新の回答を有効回答として扱います。

以前の回答は，監査・確認用の履歴として保持します。

---

##### 4. アンケートの削除

回答が存在するアンケートは，原則として物理削除しません。

不要になったアンケートは，アーカイブ状態に変更します。

SurveyTex原本，回答データ，集計結果の対応関係を維持するためです。

---

##### 5. 個人情報

回答には，ログインユーザー名を保存します。

したがって，通常の社内アンケートは匿名ではありません。

自由記述欄には，不要な個人情報や機密情報を記載しないよう，アンケート本文で案内してください。
"""


