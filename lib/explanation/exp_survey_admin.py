SURVEY_SUMMARY_TEXT = """
##### 1. 回答状況

アンケートごとに，次の情報を表示します。

- 回答者数
- 有効回答数
- 回答率
- 最初の回答日時
- 最終回答日時
- 再回答件数

回答率を算出する場合は，対象ユーザー数の設定が必要です。

---

##### 2. 選択式質問

ラジオボタン，チェックボックス，プルダウンなどの質問は，選択肢ごとに次を表示します。

- 回答人数
- 回答件数
- 回答割合
- 棒グラフ

チェックボックスは，1人が複数の選択肢を回答できるため，割合の合計が100％を超えることがあります。

---

##### 3. 数値・評価質問

数値入力や段階評価では，次の統計を表示します。

- 回答数
- 平均
- 中央値
- 最小値
- 最大値

---

##### 4. 自由記述

自由記述は，次の情報とともに一覧表示します。

- ユーザー名
- 回答日時
- 質問文
- 回答内容

---

##### 5. Excel出力

次のシートを持つExcelファイルを出力します。

- `回答者一覧`
- `回答明細`
- `質問別集計`
- `選択肢別集計`
- `自由記述`
- `アンケート定義`

通常の集計では，各ユーザーの最新の有効回答を使用します。
"""


