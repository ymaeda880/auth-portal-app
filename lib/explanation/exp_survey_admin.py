SURVEYTEX_QUESTION_TEXT = r"""
##### 1. 質問の基本形

質問は，`\\begin{質問形式, ...}` から `\\end{質問形式}` までの質問ブロックとして記述します．

```text
\begin{radio,
id="proofreading_use",
label="文章校正",
required=true,
skip_button=true
}

\question{「文章校正」を使用したことがありますか？}

\options{
1|使用したことがある
0|使用したことがない
}

\end{radio}
```

質問ブロックでは，次の3つを区別して記述します．

- `label="..."`：Excel出力や集計で使用する短い質問名
- `\\question{...}`：回答者の画面に表示する質問文
- `\\options{...}`：選択式質問の選択肢

---

##### 2. 質問ブロックの開始

`\\begin{...}` の最初に質問形式を指定し，続けて属性をカンマ区切りで記述します．

```text
\begin{textarea,
id="proofreading_comment",
label="文章校正",
required=false,
show_if="proofreading_use=='1'"
}
```

属性は1行にまとめても記述できますが，属性ごとに改行すると確認しやすくなります．

---

##### 3. 質問ID

質問IDは，`id="..."` 属性で指定します．

```text
id="proofreading_comment"
```

質問IDは必須です．英字で始め，英数字，`_`，`-` を使用してください．同じアンケート内で重複させることはできません．

---

##### 4. 集計用ラベル

`label="..."` には，質問の分類やExcel出力で使用する短い名称を記述します．

```text
label="文章校正"
```

同じ機能に関する複数の質問では，同じラベルを使用できます．

```text
label="文章校正"
label="文章校正"
label="文章校正"
```

`label` は回答者に表示する質問文ではありません．回答者に表示する文章は `\\question{...}` に記述します．

---

##### 5. 質問文

回答者に表示する質問文は，`\\question{...}` に記述します．

```text
\question{文章校正について，ご感想・ご要望をお聞かせください}
```

旧文法の `\\label{質問文}` は使用しません．

---

##### 6. 質問形式

質問形式は，`\\begin{...}` の最初の値として指定します．

| 質問形式 | 内容 |
|---|---|
| `radio` | 選択肢から1つだけ選ぶ |
| `checkbox` | 選択肢から複数選ぶ |
| `select` | プルダウンから1つ選ぶ |
| `text` | 1行の短い文章を入力する |
| `textarea` | 複数行の文章を入力する |
| `number` | 数値を入力する |
| `date` | 日付を入力する |
| `rating` | 段階評価を入力する |

`\\end{...}` には，`\\begin{...}` と同じ質問形式を指定してください．

---

##### 7. 質問属性

主な属性は次のとおりです．

- `id`
- `label`
- `required`
- `show_if`
- `help`
- `placeholder`
- `min`
- `max`
- `step`
- `max_length`
- `none_button`
- `skip_button`

`required`，`none_button`，`skip_button` は `true` または `false` で指定します．

---

##### 8. 補足説明とプレースホルダー

```text
\begin{textarea,
id="comment",
label="PAISへの意見",
required=false,
help="具体的に入力してください",
placeholder="改善してほしい点を入力してください"
}

\question{PAISについてのご意見をお書きください}

\end{textarea}
```

---

##### 9. 特別回答

質問に特別な回答を追加する場合は，`none_button` または `skip_button` を指定します．

- `none_button=true`：「該当なし」を使用できるようにします．
- `skip_button=true`：「回答をスキップする」を使用できるようにします．

例えば，利用経験を確認する質問で「回答をスキップする」を追加する場合は，次のように記述します．

```text
\begin{radio,
id="proofreading_use",
label="文章校正",
required=true,
skip_button=true
}

\question{「文章校正」を使用したことがありますか？}

\options{
1|使用したことがある
0|使用したことがない
}

\end{radio}
```

`skip_button=true` による「回答をスキップする」は，通常の選択肢とは別の特別回答として扱います．

そのため，`\\options{...}` の中に「回答をスキップする」を追加する必要はありません．

「回答をスキップする」が選択された質問は，未回答ではなく，明示的に回答をスキップしたものとして保存されます．

なお，回答画面にある「以降の回答をスキップ」は，SurveyTexの属性ではありません．

これは回答画面側の共通機能で，現在の未回答質問を含め，以降にある未回答質問をまとめてスキップするための機能です．
"""

