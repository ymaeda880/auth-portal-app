from __future__ import annotations

# ============================================================
# imports
# ============================================================
from typing import Any

import streamlit as st

from common_lib.ui.help_expander import render_themed_help_expander
from common_lib.ui.intro_panel import (
    render_info_card_compact,
    render_info_card_bullets_compact_custom,
)


# ============================================================
# ページ上部説明UI
# ============================================================
def render_userinfo_page_intro() -> None:

    # ------------------------------------------------------------
    # AI利用なし
    # ------------------------------------------------------------
    render_info_card_compact(
        body_html="""
🟢 このページでは，<b>AIは使用しません</b>．ログイン中ユーザーの氏名・メールアドレス・部署を登録または変更できます．
""",
    )

    # ------------------------------------------------------------
    # 使い方
    # ------------------------------------------------------------
    render_info_card_bullets_compact_custom(
        title="使い方 🪪",
        items=[
            ("①", "現在登録されている内容を確認してください．"),
            ("②", "姓・名・メールアドレス・部署を入力してください．"),
            ("③", "保存してください．「💾 登録 / 更新」ボタンを押すと保存されます．"),
        ],
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )


# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_userinfo_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "yellow_soft",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "userinfo_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：使い方
# ============================================================
USERINFO_USAGE_TEXT = """

##### 1. このページの役割

このページは，ログイン中ユーザー自身の基本情報を登録・変更するための画面です。<br>
登録された情報は，システム内ででユーザー名・所属・連絡先などを参照するために使用します。

---

##### 2. 登録できる情報

登録できる主な情報は次のとおりです。

- 姓
- 名
- メールアドレス
- 部署

---

##### 3. 基本的な流れ

1. 現在登録されている内容を確認します。
2. フォームに氏名・メールアドレス・部署を入力します。
3. 「💾 登録 / 更新」ボタンを押します。
4. 保存が完了すると，登録内容が更新されます。

"""


# ============================================================
# 詳細説明：入力項目
# ============================================================
USERINFO_FIELDS_TEXT = """

##### 1. 姓・名

ユーザーの氏名を入力します。<br>
姓と名は必須項目です。

---

##### 2. メールアドレス

連絡用のメールアドレスを入力します。<br>
メールアドレスは必須項目です。

---

##### 3. 部署

所属部署を選択します。<br>
選択肢に該当する部署がない場合は，「その他」を選び，自由入力欄に部署名を入力します。

"""


# ============================================================
# 詳細説明：注意事項
# ============================================================
USERINFO_FAQ_TEXT = """

##### Q1. 未ログインの場合は使えますか？

使えません。<br>
ポータルでサインインしてから使用してください。

---

##### Q2. 他のユーザーの情報を変更できますか？

変更できません。<br>
このページでは，ログイン中ユーザー自身の情報だけを登録・変更します。

---

##### Q3. 部署が選択肢にない場合は？

「その他」を選択し，自由入力欄に部署名を入力してください。

---

##### Q4. メールアドレスの形式が違う場合は？

保存時にエラーが表示されます。<br>
正しい形式のメールアドレスを入力してください。

"""


# ============================================================
# 詳細説明タブ
# ============================================================
HELP_TABS = [
    ("使い方", USERINFO_USAGE_TEXT),
    ("入力項目", USERINFO_FIELDS_TEXT),
    ("FAQ", USERINFO_FAQ_TEXT),
]