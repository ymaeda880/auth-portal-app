# ============================================================
# ページ上部説明UI
# ============================================================
def render_login_page_intro() -> None:

    # ------------------------------------------------------------
    # AI利用なし
    # ------------------------------------------------------------
    render_info_card_compact(
        body_html="""
🟢 このページでは，<b>AIは使用しません</b>．ユーザー名とパスワードを使用して，PAISポータルへログインします．
""",
    )

    # ------------------------------------------------------------
    # 使い方
    # ------------------------------------------------------------
    render_info_card_bullets_compact_custom(
        title="使い方 🔐",
        items=[
            ("▶️", "<b>ログインするとき</b>"),
            ("", "ユーザー名とパスワードを入力し，「ログイン」ボタンを押してください．"),
            ("▶️", "<b>ブラウザーの自動入力を使用するとき</b>"),
            ("", "ブラウザーに保存されているユーザー名とパスワードを選択して入力できます．"),
            ("▶️", "<b>別のユーザーでログインするとき</b>"),
            ("", "現在ログイン中の場合でも，別のユーザー名とパスワードを入力してログインできます．"),
            ("⚠️", "共用パソコンでは，ブラウザーにパスワードを保存しないでください．"),
        ],
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )


# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_login_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "light_green",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "login_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：使い方
# ============================================================
LOGIN_USAGE_TEXT = """

##### 1. このページの役割

このページは，PAISポータルへログインするための画面です。<br>
ユーザー名とパスワードを入力し，「ログイン」ボタンを押すと認証を行います。

---

##### 2. 基本的な流れ

1. ユーザー名を入力します。
2. パスワードを入力します。
3. 「ログイン」ボタンを押します。
4. 認証に成功すると，PAISポータルのログイン状態が更新されます。

---

##### 3. ブラウザーの自動入力

このページのユーザー名欄とパスワード欄は，ブラウザーのパスワード管理機能が認識しやすいように設定されています。<br>
ブラウザーにログイン情報が保存されている場合は，保存済みのユーザー名とパスワードを選択して入力できます。

ブラウザーの設定，セキュリティーポリシー，保存状態によっては，自動入力候補が表示されない場合があります。

---

##### 4. ログイン中の場合

すでにログイン中の場合は，現在のユーザー名を画面に表示します。<br>
別のユーザー名とパスワードを入力してログインすると，ログインユーザーが切り替わります。

"""


# ============================================================
# 詳細説明：注意事項
# ============================================================
LOGIN_FAQ_TEXT = """

##### Q1. パスワードをブラウザーへ保存できますか？

ブラウザーのパスワード保存機能が有効な場合は，ログイン後に保存確認が表示されることがあります。<br>
表示方法は，Chrome，Edge，Firefox，Safariなど，使用するブラウザーによって異なります。

---

##### Q2. 自動入力候補が表示されません。

次の点を確認してください。

- ブラウザーのパスワード保存機能が有効になっているか
- 対象サイトのログイン情報がブラウザーに保存されているか
- シークレットモードやプライベートブラウズを使用していないか
- 組織のセキュリティーポリシーでパスワード保存が禁止されていないか

---

##### Q3. 共用パソコンでもパスワードを保存してよいですか？

共用パソコンでは，パスワードを保存しないでください。<br>
保存すると，ほかの利用者がログインできる可能性があります。

---

##### Q4. ログインに失敗します。

ユーザー名とパスワードを確認してください。<br>
大文字・小文字，全角・半角，前後の空白に注意してください。

"""


# ============================================================
# 詳細説明タブ
# ============================================================
HELP_TABS = [
    ("使い方", LOGIN_USAGE_TEXT),
    ("FAQ", LOGIN_FAQ_TEXT),
]
