# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_inbox_bulk_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "yellow_soft",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "inbox_bulk_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：使い方
# ============================================================
INBOX_BULK_USAGE_TEXT = """

##### 1. このページの役割

このページは，ログイン中ユーザーの Inbox に格納されているファイルを検索し，複数選択して一括処理するための画面です。<br>
主に，複数ファイルの ZIP 一括ダウンロードと，一括削除を行います。

---

##### 2. このページでできること

- タグやファイル名による検索
- 種類・格納日・最終閲覧・サイズによる絞り込み
- 複数ファイルの選択
- 選択ファイルの ZIP 一括ダウンロード
- 選択ファイルの一括削除


"""


# ============================================================
# 詳細説明：検索・選択
# ============================================================
INBOX_BULK_SEARCH_TEXT = """

##### 1. 検索

検索では，タグまたはファイル名を指定できます。<br>
スペースまたはカンマで区切ると，AND検索として扱われます。

---

##### 2. 詳細検索

「検索の詳細を表示」をオンにすると，次の条件でも絞り込めます。

- ファイル種類
- 格納日
- 最終閲覧
- サイズ

---

##### 3. 一覧での選択

一覧の左側にあるチェックボックスを使って，一括処理したいファイルを選択します。<br>
選択状態はページを移動しても維持されます。

---

##### 4. 検索条件変更時の注意

検索条件を変更すると，誤操作防止のため，選択状態はいったんクリアされます。

"""


# ============================================================
# 詳細説明：ZIP
# ============================================================
INBOX_BULK_ZIP_TEXT = """

##### 1. ZIP 一括ダウンロード

選択したファイルをまとめて ZIP ファイルとしてダウンロードできます。<br>
複数の資料をまとめて手元に保存したい場合に使用します。

---

##### 2. ZIPファイル名

ZIPファイル名は任意で指定できます。<br>
拡張子 .zip が付いていない場合は，自動的に .zip が付与されます。

---

##### 3. ZIPに入れられない場合

DB上の情報と実ファイルの状態が一致していない場合，一部のファイルをZIPに入れられないことがあります。<br>
その場合は，警告として件数が表示されます。

"""


# ============================================================
# 詳細説明：一括削除
# ============================================================
INBOX_BULK_DELETE_TEXT = """

##### 1. 一括削除

選択中のファイルをまとめて削除できます。<br>
削除対象は，現在選択されている全アイテムです。

---

##### 2. DELETE入力

一括削除を実行するには，確認入力欄に DELETE と入力する必要があります。<br>
これは誤削除を防ぐための安全確認です。

---

##### 3. 削除時の注意

削除したファイルは元に戻せません。<br>
必要なファイルは，削除前にZIPダウンロードなどで保存してください。


"""


# ============================================================
# 詳細説明：FAQ
# ============================================================
INBOX_BULK_FAQ_TEXT = """


##### Q1. ページを移動すると選択は消えますか？

消えません。<br>
選択状態はページをまたいで維持されます。

---

##### Q2. 検索条件を変更すると選択はどうなりますか？

検索条件を変更すると，誤操作防止のため選択はクリアされます。

---

##### Q3. 一括削除は取り消せますか？

取り消せません。<br>
削除前に対象ファイルを十分確認してください。

"""


# ============================================================
# 詳細説明タブ
# ============================================================
HELP_TABS = [
    ("使い方", INBOX_BULK_USAGE_TEXT),
    ("検索・選択", INBOX_BULK_SEARCH_TEXT),
    ("ZIP", INBOX_BULK_ZIP_TEXT),
    ("一括削除", INBOX_BULK_DELETE_TEXT),
    ("FAQ", INBOX_BULK_FAQ_TEXT),
]