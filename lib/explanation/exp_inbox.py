# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_inbox_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "light_green",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "inbox_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：使い方
# ============================================================
INBOX_USAGE_TEXT = """

##### 1. このページの役割

このページは，ログインユーザーごとの Inbox に対して，ファイルの格納・検索・閲覧・削除を行うための画面です。<br>
PDF，Word，Excel，PPT，テキスト，画像，その他のファイルをまとめて管理できます。

---

##### 2. 基本的な流れ

1. 必要に応じて「格納を表示」を開きます。
2. タグを指定して，ファイルを Inbox に格納します。
3. タグ・ファイル名・詳細条件でファイルを検索します。
4. 一覧またはサムネイルから対象ファイルを選択します。
5. 選択したファイルについて，操作・プレビュー・詳細情報を確認します。

---

##### 3. 格納できるファイル

このページでは，未対応拡張子も含めてファイルを保存します。<br>
ファイル種別は主に次の区分で管理されます。

- PDF
- Word
- PPT
- Excel
- テキスト
- 図・画像
- その他

画像ファイルについては，格納時にサムネイル生成も行います。

---

##### 4. タグ

格納時にタグを付けることができます。<br>
タグは検索時の絞り込みに使います。

例：

- `プロジェクト/2025-001`
- `議事録/2025-002`
- `その他/確認資料`

タグを空欄にした場合は，タグなしで保存されます。

"""


# ============================================================
# 詳細説明：検索・一覧
# ============================================================
INBOX_SEARCH_TEXT = """

##### 1. 検索条件

検索では，タグとファイル名を指定できます。<br>
スペースまたはカンマで区切ると，AND検索として扱われます。

---

##### 2. 詳細条件

「検索の詳細を表示」を開くと，次の条件を指定できます。

- 種類
- 格納日
- 最終閲覧
- サイズ

種類は，PDF・Word・PPT・Excel・テキスト・画像・その他から選択できます。

---

##### 3. 並び替え

一覧では，次の条件で並び替えできます。

- 格納日
- ファイル名
- 昇順
- 降順
- 種類別にする／しない

---

##### 4. 表示項目

一覧では，必要に応じて次の項目を表示できます。

- 格納日
- 最終閲覧
- サイズ

OFF にすると，タグとファイル名が見やすくなります。

"""

# ============================================================
# 詳細説明：プレビュー・操作
# ============================================================
INBOX_PREVIEW_TEXT = """

##### 1. ファイル選択

一覧の左側にある選択欄からファイルを選ぶと，そのファイルが操作・プレビュー・詳細表示の対象になります。

選択されているファイルは，操作欄，プレビュー欄，詳細欄で共通して使用されます。<br>
操作前に，対象ファイルが正しく選択されていることを確認してください。

---

##### 2. サムネイル一覧

現在のページに表示されているファイルについて，サムネイル一覧を表示します。<br>
画像ファイルやサムネイルが生成されているファイルは，視覚的に内容を確認できます。

一覧表だけでは判別しにくい場合は，サムネイルを使って目的のファイルを確認してください。

---

##### 3. 操作

操作欄では，現在選択されているファイルに対して各種操作を行います。<br>
操作対象は，常に「一覧で選択されている1件のファイル」です。

主な操作は次のとおりです。

- <b>ダウンロード</b>：選択中のファイルを手元のPCに保存します。
- <b>タグ変更</b>：選択中のファイルに付いているタグを変更します。
- <b>削除</b>：選択中のファイルを Inbox から削除します。
- <b>他ユーザーへ送付</b>：選択中のファイルを別のユーザーの Inbox へ送付します。

<br>

<b>ダウンロード</b>は，ファイルの内容を手元で確認したい場合や，削除前にバックアップを取りたい場合に使用します。<br>
重要なファイルを削除する前には，必要に応じてダウンロードして保存してください。

<br>

<b>タグ変更</b>は，ファイルの分類を修正したい場合に使用します。<br>
たとえば，誤って「その他」として保存したファイルを「プロジェクト/2025-001」などに変更できます。<br>
タグを適切に付けておくと，後で検索しやすくなります。

<br>

<b>削除</b>は，選択中のファイルを Inbox から取り除く操作です。<br>
削除すると，一覧，サムネイル，プレビュー，詳細表示の対象から外れます。<br>
削除前には，ファイル名，タグ，プレビュー内容を確認し，対象ファイルが正しいことを十分に確認してください。

<br>

<b>他ユーザーへ送付</b>は，選択中のファイルを別ユーザーの Inbox に渡すための操作です。<br>
送付前には，送付先ユーザーとファイル内容を確認してください。<br>
特に，機密情報，個人情報，契約書，社外秘資料などが含まれる場合は，送付してよい相手かどうかを必ず確認してください。

---

##### 4. プレビュー

選択したファイルは，対応している形式でプレビューできます。<br>
PDF，Word，テキスト，画像などは，内容を確認しながら操作できます。

削除や他ユーザーへの送付を行う前には，プレビューで内容を確認することを推奨します。<br>
ファイル名だけでは判断しにくい場合でも，プレビューを見ることで誤操作を防ぎやすくなります。

---

##### 5. 詳細情報

詳細欄では，選択中ファイルに関する各種情報を確認できます。

主な確認項目は次のとおりです。

- ファイル種別
- ファイルID
- ファイル名
- タグ
- 保存日時
- その他の管理情報

似た名前のファイルが複数ある場合は，詳細情報を確認して対象ファイルを特定してください。

---

##### 6. 注意事項

- 操作，プレビュー，詳細表示は，現在選択中のファイルを対象として行われます。
- 操作前には，必ず選択中のファイル名と内容を確認してください。
- 削除前には，必要に応じてダウンロードしてバックアップを取得してください。
- 他ユーザーへ送付する前には，送付先とファイル内容を確認してください。
- 機密情報や個人情報を含むファイルは，送付先を特に慎重に確認してください。
- タグを変更すると，検索結果に表示される条件が変わる場合があります。
- Inbox はログインユーザーごとに分離されており，他のユーザーの Inbox は表示されません。

"""

# ============================================================
# 詳細説明：注意事項
# ============================================================
INBOX_FAQ_TEXT = """

##### Q1. Inbox はユーザーごとに分かれていますか？

はい。Inbox はログインユーザーごとに分かれています。<br>
ログイン中のユーザーに対応する保存領域のみを操作します。

---

##### Q2. 容量上限を超えるとどうなりますか？

容量上限を超える場合，ファイルは保存されません。<br>
現在の使用量，追加予定サイズ，上限が画面に表示されます。

---

##### Q3. 未対応の拡張子は保存できますか？

はい。未対応拡張子も保存します。<br>
ただし，種別は「その他」として扱われる場合があります。

---

##### Q4. xls ファイルはどう扱われますか？

xls ファイルは，通常「その他」として格納されます。<br>
必要に応じて，事前に xlsx 形式へ変換してください。

"""


