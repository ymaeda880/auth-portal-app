            ("", "ユーザー名とパスワードを入力してログインします．ログイン後は，利用可能なアプリが表示されます．"),
            ("▶️", "<b>別ユーザーでサインインするとき</b>"),
            ("", "ログイン中でも，別ユーザーでサインインする操作により，ログインフォームを再表示できます．"),
