def render_internal_survey_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "light_green",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "internal_survey_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：回答方法
# ============================================================
SURVEY_USAGE_TEXT = """

##### 1. このページの役割

このページは，管理者が実施している社内アンケートに回答するための画面です．

回答内容は，PAISの機能，操作画面，説明方法，運用方法などの改善に使用します．

---

##### 2. アンケートの実施状態

実施中のアンケートがある場合は，次の情報を表示します．

- アンケートのタイトル
- アンケートの説明
- 回答期限
- 回答状況

実施中のアンケートがない場合は，現在はアンケートを実施していないことを表示します．

開始日時より前のアンケートや，終了日時を過ぎたアンケートには回答できません．

---

##### 3. アンケートの開始

「アンケートを開始」を押すと，最初の質問が表示されます．

質問は1画面に1問ずつ表示されます．

回答後に「次へ」を押すと，次の質問へ進みます．

---

##### 4. 前の質問へ戻る

「戻る」を押すと，直前に表示された質問へ戻ります．

条件分岐によって質問がスキップされている場合は，定義上の直前の質問ではなく，実際に表示された直前の質問へ戻ります．

「最初に戻る」を押すと，アンケートの最初の質問へ戻ります．

---

##### 5. 回答をスキップする

質問によっては，「回答をスキップする」を選択できます．

「回答をスキップする」を選んだ質問は，未回答ではなく，回答をスキップしたものとして扱われます．

また，「以降の回答をスキップ」を押すと，現在の未回答質問を含め，以降にある未回答質問をまとめてスキップし，回答内容の確認画面へ進みます．

すでに回答済みの質問は，「以降の回答をスキップ」を押しても上書きされません．

---

##### 6. 回答中の保持

入力した回答は，アンケートを開いている間，画面の移動に合わせて保持されます．

回答内容の確認画面で「途中で保存」を押すと，その時点までの回答内容をサーバーに保存できます．

途中保存したアンケートは，後から再度開いて「回答を再開」を押すことで，保存した回答内容から続きを回答できます．

"""


# ============================================================
# 詳細説明：質問の表示
# ============================================================
SURVEY_QUESTION_TEXT = """

##### 1. 質問形式

アンケートでは，次の質問形式を使用できます．

- 1つの選択肢を選ぶ質問
- 複数の選択肢を選ぶ質問
- 選択リストから選ぶ質問
- 短い文章を入力する質問
- 長い文章を入力する質問
- 数値を入力する質問
- 日付を入力する質問
- 段階評価を選ぶ質問

質問形式は，アンケートの内容に応じて管理者が設定します．

---

##### 2. 必須回答

必須と表示された質問には回答が必要です．

ただし，「回答をスキップする」が用意されている質問では，「回答をスキップする」を選択できます．

必須質問が未回答のままの場合は，次の質問へ進むときや回答を送信するときにメッセージが表示されます．

任意の質問は，回答せずに次へ進むことができます．

---

##### 3. 入力条件

質問によって，次のような入力条件が設定される場合があります．

- 選択できる回答の範囲
- 入力できる最小値と最大値
- 数値の刻み幅
- 入力できる最大文字数
- 日付の入力形式

入力内容が条件に合わない場合は，画面にメッセージが表示されます．

---

##### 4. 条件付き質問

前の質問への回答に応じて，表示される質問が変わる場合があります．

表示条件を満たさない質問は自動的にスキップされ，回答者には表示されません．

例えば，ある機能を「使用したことがない」または「回答をスキップする」とした場合，その機能についての詳しい評価質問が表示されないことがあります．

前の回答を変更すると，それまで表示されていた後続の質問が非表示になる場合があります．

---

##### 5. 進捗表示

アンケート回答中は，現在の回答位置を表示します．

例えば，41問中の1問目の場合は，画面上部に「Q1 / 41」のように表示します．

条件分岐によって途中の質問が表示されない場合でも，質問番号はアンケート定義上の番号を表示します．

"""


# ============================================================
# 詳細説明：回答確認・送信
# ============================================================
SURVEY_SUBMIT_TEXT = """

##### 1. 回答確認

最後の質問まで進むか，「以降の回答をスキップ」を押すと，回答内容の確認画面を表示します．

確認画面では，実際に表示対象となった質問と回答を一覧で確認できます．

「回答をスキップする」とした質問は，そのことが分かる形で表示されます．

表示条件を満たさず，自動的に非表示になった質問は確認画面に表示されません．

---

##### 2. 回答の修正

回答を修正する場合は，「質問へ戻る」を押して質問画面へ戻ります．

前の回答を変更した結果，表示条件を満たさなくなった質問の回答は，正式な回答の保存対象から除外される場合があります．

---

##### 3. 途中で保存

回答内容の確認画面で「途中で保存」を押すと，その時点までの回答内容を保存できます．

途中保存した回答は正式な回答ではなく，「回答途中」の状態として保存されます．

後からアンケートを開くと，「回答途中です」と表示され，「回答を再開」から続きを回答できます．

---

##### 4. 回答の送信

回答内容を確認して「回答を送信」を押すと，正式な回答として保存されます．

送信時には，必須回答や各質問の入力条件をもう一度確認します．

入力内容に問題がある場合は回答を正式保存せず，修正が必要な質問を表示します．

---

##### 5. 保存される情報

回答の送信時には，主に次の情報を保存します．

- ログインユーザーの識別情報
- 回答日時
- アンケートID
- アンケート定義のバージョン
- 質問ごとの回答内容
- 回答をスキップした情報
- 再回答の回数
- 回答状態
- アンケート定義との対応情報

---

##### 6. 送信完了

回答が正常に保存されると，受付完了メッセージと回答日時を表示します．

「途中で保存」の状態では正式な回答にはなりません．

「回答を送信」を押して正常に保存された回答が正式な回答となります．

"""


# ============================================================
# 詳細説明：回答済み・再回答
# ============================================================
SURVEY_REANSWER_TEXT = """

##### 1. 回答途中の場合

途中保存したアンケートを開くと，「回答途中です」と表示されます．

「回答を再開」を押すと，保存した回答内容を読み込み，続きを回答できます．

---

##### 2. 回答済みの場合

すでに正式に回答しているアンケートを開いた場合は，回答済みであることと，前回の回答日時を表示します．

通常は，1人につき1件の現在回答を保持します．

---

##### 3. 再回答

回答済みのアンケートには，再回答できます．

「再回答する」を押すと，前回の回答内容を読み込んでアンケートを開始します．

回答内容を修正して「途中で保存」すると，回答は「回答途中」の状態になります．

最後に「回答を送信」を押すと，新しい内容が正式な回答として保存されます．

再回答前の正式回答は履歴として保存されます．

---

##### 4. 再回答の途中保存

再回答中でも「途中で保存」を使用できます．

途中保存した内容は，後から「回答を再開」して続きを編集できます．

最終的に「回答を送信」を押した時点で，その内容が正式な回答になります．

"""


# ============================================================
# 詳細説明：保存される情報
# ============================================================
SURVEY_DATA_TEXT = """

##### 1. 匿名回答について

このアンケートは匿名アンケートではありません．

回答には，ログインユーザーの識別情報が関連付けられます．

---

##### 2. 回答の利用目的

回答内容は，主に次の目的で使用します．

- PAISの機能改善
- 操作画面の改善
- 利用状況の確認
- 運用上の課題の把握
- 社内研修や説明方法の改善
- 新しい機能の検討

---

##### 3. 回答状態

アンケートの回答には，主に次の状態があります．

- 回答途中
- 回答済み

「途中で保存」を行った回答は「回答途中」として保存されます．

「回答を送信」を行い，正常に保存された回答は「回答済み」として扱われます．

---

##### 4. 回答の正本

正式に送信された回答内容は，アンケートの回答データとして保存されます．

再回答を行った場合は，新しく正式送信された内容が現在の回答になります．

以前の正式回答は，再回答履歴として保存される場合があります．

検索，一覧表示，回答状況の確認，集計などに必要な管理情報も保存されます．

---

##### 5. AIの利用

このアンケートページでは，質問の表示，回答の入力，回答の保存にAIは使用しません．

回答内容の分析などにAIを利用する場合は，利用目的や取り扱い方法を別途明示します．

"""


# ============================================================
# 詳細説明：回答期限・FAQ
# ============================================================
SURVEY_FAQ_TEXT = """

##### Q1. 回答できる期間はいつまでですか？

アンケートに設定された終了日時まで回答できます．

開始日時より前のアンケートには回答できません．

終了日時を過ぎたアンケートには，新規回答も再回答もできません．

---

##### Q2. 回答途中で期限を過ぎた場合はどうなりますか？

回答の送信時にも，アンケートが実施中かどうかを確認します．

途中保存した回答があっても，終了日時を過ぎた後は正式に送信できません．

---

##### Q3. 回答途中の内容は保存されますか？

はい．

回答内容の確認画面で「途中で保存」を押すと，その時点までの回答内容が保存されます．

後からアンケートを開き，「回答を再開」から続きを回答できます．

---

##### Q4. ブラウザーを閉じた場合はどうなりますか？

「途中で保存」を行っていない回答内容は，ブラウザーを閉じたり，ログアウトしたりすると失われることがあります．

中断する場合は，回答内容の確認画面で「途中で保存」を行ってください．

---

##### Q5. 前の回答を変更できますか？

「戻る」を押すと，前の質問へ戻って回答を変更できます．

「最初に戻る」を押すと，最初の質問へ戻ることができます．

前の回答を変更すると，回答条件に応じて後続の質問が表示または非表示になる場合があります．

---

##### Q6. 回答したくない質問がある場合はどうしますか？

スキップできる質問では，「回答をスキップする」を選択できます．

また，残りの質問への回答を終了したい場合は，「以降の回答をスキップ」を使用できます．

「以降の回答をスキップ」を押すと，現在の未回答質問を含め，以降の未回答質問がまとめてスキップされ，回答内容の確認画面へ進みます．

---

##### Q7. 質問数が途中で変わることはありますか？

条件付き質問がある場合は，前の回答に応じて表示される質問が変わることがあります．

ただし，画面に表示される質問番号は，アンケート全体の質問番号を基準にしています．

---

##### Q8. 回答内容は誰が確認しますか？

回答内容は，アンケートを管理するPAISの管理者が確認します．

ログインユーザーの識別情報を含めて保存するため，匿名アンケートではありません．

---

##### Q9. 送信後に回答を修正できますか？

再回答が許可されているアンケートでは，再回答できます．

前回回答を読み込んで修正し，再度「回答を送信」すると，新しい内容が正式な回答になります．

"""


