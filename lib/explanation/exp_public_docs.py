from typing import Any

import streamlit as st

from common_lib.ui.help_expander import render_themed_help_expander
from common_lib.ui.intro_panel import (
    render_info_card_compact,
    render_info_card_bullets_compact_custom,
)


# ============================================================
# ページ上部説明UI
# ============================================================
def render_public_docs_page_intro() -> None:

    # ------------------------------------------------------------
    # AI利用なし
    # ------------------------------------------------------------
    render_info_card_compact(
        body_html="""
🟢 このページでは，<b>AIは使用しません</b>．管理者が共有した社内文書を閲覧・ダウンロードできます．
""",
    )

    # ------------------------------------------------------------
    # 使い方
    # ------------------------------------------------------------
    render_info_card_bullets_compact_custom(
        title="使い方 📚",
        items=[
            ("", "②の一覧から文書を選択してください．"),
            ("", "③の操作からダウンロードできます．また④のプレビューでパソコン上で閲覧ができます．"),
            ("", "①の検索からタグまたはファイル名を入力して，文書の検索ができます．"),
        ],
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )


# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_public_docs_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "light_green",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "public_docs_help_expander"
HELP_EXPANDER_TITLE = "詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：使い方
# ============================================================
PUBLIC_DOCS_USAGE_TEXT = """

##### 1. このページの役割

このページは，管理者が admin Inbox に格納した社内共有文書を，一般ユーザーが閲覧・ダウンロードするための画面です。<br>
文書の登録・削除・タグ変更はこのページでは行いません。

---

##### 2. 基本的な流れ

1. タグまたはファイル名で文書を検索します。
2. 一覧から対象文書を選択します。
3. 操作欄で文書情報を確認します。
4. 必要に応じて文書をダウンロードします。
5. プレビューで内容を確認します。

---

##### 3. 文書の登録場所

このページでは，管理者用 Inbox に格納された文書を表示します。<br>
文書の登録は，管理者が既存の Inbox 操作ページから行います。

例：

- PAISマニュアル
- AIガイドライン
- 操作説明資料
- 社内ルール文書

"""


# ============================================================
# 詳細説明：検索・一覧
# ============================================================
PUBLIC_DOCS_SEARCH_TEXT = """

##### 1. 検索

検索では，次の条件を指定できます。

- タグ
- ファイル名

スペースまたはカンマで区切ると，AND検索として扱われます。

---

##### 2. 一覧

検索条件に一致した文書が一覧表示されます。<br>
一覧の左側にあるラジオボタンで，閲覧したい文書を1件選択します。

---

##### 3. ページング

文書が多い場合は，前へ・次へボタンでページを移動します。<br>
ページを移動すると，選択状態はいったん解除されます。

"""


# ============================================================
# 詳細説明：操作・プレビュー
# ============================================================
PUBLIC_DOCS_PREVIEW_TEXT = """

##### 1. 操作

操作欄では，選択中の文書について，基本情報の確認とダウンロードを行います。

表示される主な情報は次のとおりです。

- 種別
- タグ
- 元ファイル名
- 追加日時
- サイズ
- 最終閲覧

---

##### 2. ダウンロード

ダウンロードボタンを押すと，選択中の文書を手元のPCに保存できます。<br>
文書を保存して確認したい場合や，オフラインで参照したい場合に使用します。

---

##### 3. プレビュー

選択した文書は，対応している形式でプレビューできます。<br>
PDF，Word，テキスト，画像などは，画面上で内容を確認できます。

---

##### 4. このページで行わない操作

このページは閲覧用です。<br>
次の操作は行いません。

- タグ変更
- 削除
- 他ユーザーへの送付
- 新規ファイルの格納

"""


# ============================================================
# 詳細説明：注意事項
# ============================================================
PUBLIC_DOCS_FAQ_TEXT = """

##### Q1. 誰の Inbox を見ていますか？

このページでは，admin Inbox に格納された社内共有文書を表示します。<br>
ログイン中ユーザー自身の Inbox ではありません。

---

##### Q2. 最終閲覧とは何ですか？

最終閲覧は，admin Inbox 上の文書が最後にプレビューされた時刻です。<br>
このページでは，全ユーザー共通の最終閲覧時刻として扱います。

---

##### Q3. 文書を削除できますか？

このページでは削除できません。<br>
文書の削除やタグ変更は，管理者が既存の Inbox 操作ページから行います。

---

##### Q4. 文書が表示されない場合は？

管理者が admin Inbox に文書を格納していない可能性があります。<br>
また，検索条件が厳しすぎる場合も表示されません。

"""


# ============================================================
# 詳細説明タブ
# ============================================================
HELP_TABS = [
    ("使い方", PUBLIC_DOCS_USAGE_TEXT),
    ("検索・一覧", PUBLIC_DOCS_SEARCH_TEXT),
    ("操作・プレビュー", PUBLIC_DOCS_PREVIEW_TEXT),
    ("FAQ", PUBLIC_DOCS_FAQ_TEXT),
]